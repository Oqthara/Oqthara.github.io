// Detect language structures that the highlighter grammar does not know about.
//
// Why this exists
// ---------------
// `src/lib/oqthara-grammar.js` is a hand-written Prism grammar whose lists are asserted in
// its own comments to be exact: the keyword list is "those keywords, not an approximation",
// and the builtin list was "taken from the generated standard library reference". Nothing
// enforced either claim. When this audit was written the grammar was missing the `const`
// keyword and 70 of the 155 global functions the reference lists, so a large share of the
// language was rendered as plain identifiers with no structural colouring at all.
//
// The previous guard could not catch that: `tests/inference.test.js` compares `OQ_KEYWORDS`
// against a second hardcoded array in the test, so the two copies could only disagree with
// each other, never with the language.
//
// What counts as ground truth
// ---------------------------
// `docs/stdlib/reference.md` in the canonical repository, generated by `oq doc` from the
// implementation. It carries a `## Keywords` list and a `## Global functions` table, so the
// comparison is against the language rather than against another transcription of it. Lexing
// that page is safe precisely because it is machine-generated: it is the one document whose
// contents cannot have been written by hand in a way that disagrees with the code.
//
// Scope
// -----
// Four checks, one per hardcoded structure in the grammar:
//
//   * `OQ_KEYWORDS` against the reference's `## Keywords` section;
//   * `OQ_BUILTINS` plus `OQ_STATEMENT_BUILTINS` against `## Global functions`;
//   * `OQ_RANGE_OPERATORS` against the range operators the parser recognises;
//   * the grammar's operator rule against the lexer's two-character operator table;
//   * `OQ_CONTEXTUAL_KEYWORDS` against the words the parser reads by position.
//
// The last three have no generated artefact, so they are read from the language repository's
// parser and lexer -- from GitHub by default, or from a checkout with `--local`. If a source cannot be
// read the check is reported as not evaluated rather than as a pass. The distinction matters: a
// check that silently does nothing is worse than no check, because the absence of a failure is
// read as evidence.
//
// Exit codes
// ----------
//   0  the grammar covers everything the reference lists
//   1  usage error
//   2  drift: at least one structure is missing from or unknown to the grammar
//   3  the reference could not be read
//
// Usage
//   node scripts/audit-grammar.mjs                      # audit against GitHub
//   node scripts/audit-grammar.mjs --local=/path/repo   # audit against a checkout
//   node scripts/audit-grammar.mjs --json               # machine-readable report

import { readFileSync } from "node:fs";
import { join } from "node:path";

const REPO = "Oqthara/oqthara";
const DEFAULT_REF = "main";

/** The generated reference, the only hand-editing-proof description of the language. */
const REFERENCE_PATH = "docs/stdlib/reference.md";
const PARSER_PATH = "oq-core/src/main/java/dev/oqthara/core/Parser.java";
const LEXER_PATH = "oq-core/src/main/java/dev/oqthara/core/Lexer.java";

const GRAMMAR_PATH = "src/lib/oqthara-grammar.js";

/**
 * Names the grammar is knowingly missing, with the reason.
 *
 * Empty is the healthy state. An entry here is a documented decision, not a silenced failure,
 * and the audit reports how many it suppressed so a growing map stays visible.
 */
const ALLOWED_MISSING = new Map();

function usage(message) {
  if (message) console.error(`audit-grammar: ${message}`);
  console.error("usage: node scripts/audit-grammar.mjs [--local=<dir>] [--ref=<branch>] [--json]");
  process.exit(1);
}

function parseArgs(argv) {
  const options = { local: "", ref: DEFAULT_REF, json: false };
  for (const arg of argv) {
    if (arg === "--json") options.json = true;
    else if (arg.startsWith("--local=")) options.local = arg.slice("--local=".length);
    else if (arg.startsWith("--ref=")) options.ref = arg.slice("--ref=".length) || DEFAULT_REF;
    else usage(`unknown argument ${JSON.stringify(arg)}`);
  }
  return options;
}

/**
 * Every `export const NAME = [...]` string array in the grammar, keyed by NAME.
 *
 * Reading the source rather than importing it keeps the audit able to explain a malformed file
 * instead of crashing on it, and matches how the existing tests already reach in.
 */
export function readGrammarArrays(source) {
  const arrays = new Map();
  const declaration = /export const ([A-Z][A-Z0-9_]*) = \[([\s\S]*?)\];/g;
  for (const match of source.matchAll(declaration)) {
    arrays.set(match[1], [...match[2].matchAll(/"([^"]+)"/g)].map((entry) => entry[1]));
  }
  return arrays;
}

/** The keywords the reference says the language has. */
export function referenceKeywords(markdown) {
  const section = /## Keywords\n\n(.*?)\n/.exec(markdown);
  if (!section) return null;
  const names = [...section[1].matchAll(/`([^`]+)`/g)].map((entry) => entry[1]);
  return names.length > 0 ? names : null;
}

/**
 * The global functions the reference says exist.
 *
 * The table is read row by row: a row whose first cell is a bare snake_case name in backticks,
 * before the next `## ` heading, is one global function.
 */
export function referenceFunctions(markdown) {
  const start = markdown.indexOf("## Global functions");
  if (start < 0) return null;
  const rest = markdown.slice(start + "## Global functions".length);
  const next = rest.search(/\n## /);
  const section = next < 0 ? rest : rest.slice(0, next);
  const names = [...section.matchAll(/^\|\s*`([a-z][a-z0-9_]*)`\s*\|/gm)].map((entry) => entry[1]);
  return names.length > 0 ? names : null;
}

/** The contextual range operators the parser recognises. */
export function parserRangeOperators(source) {
  // `to` and `until` are contextual: the parser accepts them only where a range can start, so
  // they are tested by string equality rather than declared as tokens. Collecting every name
  // that appears in such a comparison is what keeps this from needing the grammar of the
  // parser itself.
  const names = new Set();
  for (const match of source.matchAll(/\.equals\("([a-z]+)"\)/g)) names.add(match[1]);
  // `RANGE_OPERATORS = Set.of("to", "until")` is the shape a refactor would most likely take;
  // accepting it means the audit keeps working if the parser gains a declaration.
  const declared = /RANGE_OPERATORS\s*=\s*(?:Set|List)\.of\(([^)]*)\)/.exec(source);
  if (declared) for (const match of declared[1].matchAll(/"([^"]+)"/g)) names.add(match[1]);
  const filtered = [...names].filter((name) => name === "to" || name === "until").sort();
  return filtered.length > 0 ? filtered : null;
}

/**
 * The declaration and body words the parser reads by position rather than as tokens.
 *
 * `class`, `contract`, `init`, `immutable` and `implements` are identifiers everywhere else, so
 * they cannot be lexer keywords -- `immutable = 1` names a variable (ADR-0028). The parser
 * recognises them by comparing the lexeme, which is the same shape `to` and `until` take, so the
 * same kind of reading finds them.
 *
 * Candidate words are taken from every string literal the parser compares a lexeme against, then
 * narrowed to the ones the lexer does *not* already declare. That narrowing is what tells a
 * contextual word apart from an ordinary keyword the parser happens to test for: `if`, `else`,
 * `end`, `fun`, `data` and `catch` all appear in such comparisons and all are real tokens.
 *
 * The lexer's keyword set is passed in rather than hardcoded, so the split cannot drift from it.
 * `to` and `until` are subtracted for the same reason: the range-operator check already owns them,
 * and reporting them twice would make one missing rule look like two.
 */
export function parserContextualKeywords(source, lexerKeywords, rangeOperators) {
  const reserved = new Set([...(lexerKeywords ?? []), ...(rangeOperators ?? [])]);
  const compared = new Set();
  // `peek().lexeme().equals("class")` and `matchKeyword("else")` are the two spellings the
  // parser uses; reading only one missed whichever style a given construct happened to use.
  for (const match of source.matchAll(/\.equals\("([a-z_]+)"\)/g)) compared.add(match[1]);
  for (const match of source.matchAll(/matchKeyword\("([a-z_]+)"\)/g)) compared.add(match[1]);
  const contextual = [...compared].filter((word) => !reserved.has(word)).sort();
  return contextual.length > 0 ? contextual : null;
}

/** The keywords the lexer declares, as the reserved set. */
export function lexerKeywords(source) {
  const declared = /KEYWORDS\s*=\s*Set\.of\(([\s\S]*?)\)/.exec(source);
  if (!declared) return null;
  const names = [...declared[1].matchAll(/"([^"]+)"/g)].map((match) => match[1]).sort();
  return names.length > 0 ? names : null;
}

/**
 * The multi-character operators the lexer recognises.
 *
 * These are declared in `Lexer.TWO_CHAR`, so unlike the word operators they are a real table and
 * can be read directly. A one-character operator is not collected: the grammar's pattern ends in
 * a character class that already covers all of them, and listing 20 single characters would report
 * noise rather than drift. What this catches is a new two-character operator -- the shape a
 * language grows by -- added to the lexer and forgotten in the grammar.
 */
export function lexerOperators(source) {
  const table = /TWO_CHAR\.put\("([^"]+)"/g;
  const names = [...source.matchAll(table)].map((entry) => entry[1]);
  return names.length > 0 ? [...new Set(names)].sort() : null;
}

/**
 * The multi-character operators the grammar's operator pattern recognises.
 *
 * The grammar writes one alternation, ending in a character class for the single-character
 * operators. Only the literal alternatives before that class are operators in their own right,
 * so they are read separately from the class.
 */
export function grammarOperators(source) {
  // The rule is written as `operator: /\*\*|->|[-+*/%=<>!|]=?/,` -- one line per rule, so the
  // first match is the top-level operator rule rather than the one inside string interpolation.
  const rule = /^\s*operator:\s*\/(.+?)\/,\s*$/m.exec(source);
  if (!rule) return null;
  const body = rule[1];
  const classStart = body.lastIndexOf("[");
  // The class covers the single-character operators, so the literal alternatives are only what
  // precedes it: here `**` and `->`.
  const literals = (classStart < 0 ? body : body.slice(0, classStart))
    .split("|")
    .map((part) => part.replace(/\\/g, ""))
    .filter((part) => part.length > 0);
  const classBody = classStart < 0 ? "" : body.slice(classStart + 1, body.lastIndexOf("]"));
  const optional = /=\?$/.test(body.slice(body.lastIndexOf("]") + 1));
  return {
    literals: [...new Set(literals)],
    // A character class is a set of first characters, so with a trailing `=?` it matches either
    // the character alone or the character followed by `=`.
    classChars: classBody.replace(/\\/g, ""),
    optionalEquals: optional,
  };
}

/**
 * Two-character operators the grammar does not colour.
 *
 * Coverage, not set equality: the grammar names `**` and `->` as literals and covers the rest
 * with a character class plus an optional `=`, which is a more compact spelling of the same
 * table. Comparing sets would report `+=` as missing from a grammar that plainly handles it, so
 * the check asks whether each declared operator can be matched at all.
 */
export function uncoveredOperators(operators, grammar) {
  if (!operators || !grammar) return null;
  const missing = operators.filter((operator) => {
    if (grammar.literals.includes(operator)) return false;
    if (operator.length === 1) return !grammar.classChars.includes(operator);
    const [first, ...rest] = operator;
    if (rest.length === 1 && rest[0] === "=") return !(grammar.optionalEquals && grammar.classChars.includes(first));
    return true;
  });
  return { missing: missing.sort(), canonical: operators.length };
}

async function readRemote(path, ref) {
  const url = `https://raw.githubusercontent.com/${REPO}/${encodeURIComponent(ref)}/${path}`;
  const response = await fetch(url, { headers: { Accept: "text/plain" } });
  if (!response.ok) {
    throw new Error(`could not read ${path} at ${ref}: HTTP ${response.status}`);
  }
  return response.text();
}

function compare(grammar, canonical, allowed = ALLOWED_MISSING) {
  const site = new Set(grammar);
  const real = new Set(canonical);
  return {
    missing: [...real].filter((name) => !site.has(name) && !allowed.has(name)).sort(),
    unknown: [...site].filter((name) => !real.has(name)).sort(),
    suppressed: [...real].filter((name) => !site.has(name) && allowed.has(name)).sort(),
  };
}

function reportHuman(result) {
  const lines = [];
  for (const check of result.checks) {
    if (!check.evaluated) {
      lines.push(`- ${check.name}: not evaluated (${check.reason})`);
      continue;
    }
    const parts = [];
    if (check.missing.length) parts.push(`missing ${check.missing.join(", ")}`);
    if (check.unknown.length) parts.push(`unknown ${check.unknown.join(", ")}`);
    if (check.suppressed?.length) parts.push(`${check.suppressed.length} knowingly omitted`);
    lines.push(`- ${check.name} (${check.canonical} canonical): ${parts.length ? parts.join("; ") : "in step"}`);
  }
  return lines.join("\n");
}

async function main() {
  const options = parseArgs(process.argv.slice(2));

  const grammarSource = readFileSync(GRAMMAR_PATH, "utf8");
  const arrays = readGrammarArrays(grammarSource);
  for (const required of [
    "OQ_KEYWORDS",
    "OQ_BUILTINS",
    "OQ_STATEMENT_BUILTINS",
    "OQ_CONTEXTUAL_KEYWORDS",
  ]) {
    if (!arrays.has(required)) {
      console.error(`audit-grammar: ${GRAMMAR_PATH} no longer declares ${required}`);
      process.exit(3);
    }
  }

  const readSource = (path) =>
    options.local
      ? readFileSync(join(options.local, path), "utf8")
      : readRemote(path, options.ref);

  let reference;
  let rangeOperators = null;
  let operators = null;
  let contextual = null;
  try {
    reference = await readSource(REFERENCE_PATH);
    try {
      const parserSource = await readSource(PARSER_PATH);
      rangeOperators = parserRangeOperators(parserSource);
      contextual = parserContextualKeywords(
        parserSource,
        lexerKeywords(await readSource(LEXER_PATH)),
        rangeOperators,
      );
    } catch {
      rangeOperators = null;
      contextual = null;
    }
    try {
      operators = uncoveredOperators(lexerOperators(await readSource(LEXER_PATH)), grammarOperators(grammarSource));
    } catch {
      operators = null;
    }
  } catch (error) {
    console.error(`audit-grammar: ${error.message}`);
    process.exit(3);
  }

  const keywords = referenceKeywords(reference);
  const functions = referenceFunctions(reference);
  if (!keywords || !functions) {
    console.error(
      `audit-grammar: ${REFERENCE_PATH} no longer has a parseable Keywords section and Global functions table`,
    );
    process.exit(3);
  }

  const checks = [
    {
      name: "keywords",
      evaluated: true,
      canonical: keywords.length,
      ...compare(arrays.get("OQ_KEYWORDS"), keywords),
    },
    {
      name: "global functions",
      evaluated: true,
      canonical: functions.length,
      ...compare([...arrays.get("OQ_BUILTINS"), ...arrays.get("OQ_STATEMENT_BUILTINS")], functions),
    },
    {
      name: "range operators",
      evaluated: rangeOperators !== null,
      reason: rangeOperators === null ? "the parser could not be read" : "",
      canonical: rangeOperators?.length ?? 0,
      ...compare(arrays.get("OQ_RANGE_OPERATORS") ?? [], rangeOperators ?? []),
    },
    {
      name: "contextual keywords",
      evaluated: contextual !== null,
      reason: contextual === null ? "the parser or lexer could not be read" : "",
      canonical: contextual?.length ?? 0,
      ...compare(arrays.get("OQ_CONTEXTUAL_KEYWORDS") ?? [], contextual ?? []),
    },
    {
      name: "operator coverage",
      evaluated: operators !== null,
      reason: operators === null ? "the lexer or the grammar operator rule could not be read" : "",
      canonical: operators?.canonical ?? 0,
      missing: operators?.missing ?? [],
      unknown: [],
    },
  ];

  const drift = checks.some(
    (check) => check.evaluated && (check.missing.length > 0 || check.unknown.length > 0),
  );
  const result = { ref: options.local || options.ref, drift, checks };

  if (options.json) {
    console.log(JSON.stringify(result, null, 2));
  } else {
    console.log(`Oqthara grammar audit against ${result.ref}`);
    console.log(reportHuman(result));
    console.log(drift ? "\nDRIFT: the grammar does not cover the language." : "\nNo drift.");
  }
  process.exit(drift ? 2 : 0);
}

// Only run when invoked directly, so the parsers above stay unit-testable.
if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  await main();
}
